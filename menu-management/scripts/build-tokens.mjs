import { readFile, writeFile } from 'node:fs/promises'

const sourceUrl = new URL('../../design/montage.tokens.json', import.meta.url)
const outputUrl = new URL('../src/tokens.css', import.meta.url)

const tokens = JSON.parse(await readFile(sourceUrl, 'utf8'))

const toKebabCase = (value) =>
  String(value)
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/[^a-zA-Z0-9-]+/g, '-')
    .toLowerCase()

const collectTokens = (node, path = [], result = []) => {
  if (!node || typeof node !== 'object') return result

  if (Object.hasOwn(node, 'value') && Object.hasOwn(node, 'type')) {
    result.push({ path, value: node.value })
    return result
  }

  for (const [key, value] of Object.entries(node)) {
    collectTokens(value, [...path, toKebabCase(key)], result)
  }

  return result
}

const renderValue = (value) =>
  typeof value === 'string' || typeof value === 'number'
    ? String(value)
    : JSON.stringify(value)

const declarations = []

for (const token of collectTokens(tokens.color.atomic, ['color', 'atomic'])) {
  declarations.push(`  --${token.path.join('-')}: ${renderValue(token.value)};`)
}

for (const token of collectTokens(tokens.color.semantic.light, ['color'])) {
  declarations.push(`  --${token.path.join('-')}: ${renderValue(token.value)};`)
}

const tokenGroups = [
  ['spacing', 'space'],
  ['radius', 'radius'],
  ['opacity', 'opacity'],
  ['breakpoint', 'breakpoint'],
  ['zIndex', 'z-index'],
  ['shadow', 'shadow'],
  ['platform', 'platform'],
  ['fontWeight', 'font-weight'],
]

for (const [sourceKey, cssPrefix] of tokenGroups) {
  for (const token of collectTokens(tokens[sourceKey], [cssPrefix])) {
    declarations.push(`  --${token.path.join('-')}: ${renderValue(token.value)};`)
  }
}

for (const [name, token] of Object.entries(tokens.typography)) {
  const tokenName = toKebabCase(name)
  declarations.push(`  --type-${tokenName}-size: ${token.value.fontSize};`)
  declarations.push(`  --type-${tokenName}-line: ${token.value.lineHeight};`)
  declarations.push(`  --type-${tokenName}-tracking: ${token.value.letterSpacing};`)
}

const darkDeclarations = collectTokens(tokens.color.semantic.dark, ['color']).map(
  (token) => `  --${token.path.join('-')}: ${renderValue(token.value)};`,
)

const typeClasses = Object.keys(tokens.typography)
  .map((name) => {
    const tokenName = toKebabCase(name)
    return `.type-${tokenName} {
  font-size: var(--type-${tokenName}-size);
  line-height: var(--type-${tokenName}-line);
  letter-spacing: var(--type-${tokenName}-tracking);
}`
  })
  .join('\n\n')

const output = `/* This file is generated by scripts/build-tokens.mjs. */
:root {
${declarations.join('\n')}
}

[data-theme='dark'] {
${darkDeclarations.join('\n')}
}

${typeClasses}
`

await writeFile(outputUrl, output, 'utf8')

console.log(`Generated ${outputUrl.pathname}`)
